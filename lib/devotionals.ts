/**
 * ============================================================
 * DEVOTIONALS - Church for Truckers' syndicated set
 * ============================================================
 *
 * 365 devotionals, ported verbatim from the YourLife CC project
 * (app/js/faith.js, `const DEVOTIONALS`). They are SYNDICATED, not written by
 * this church - which is the decision FF-30 was deferring. See that entry.
 *
 * "server-only" IS LOAD-BEARING, NOT DECORATION.
 *
 * This file is roughly 237 KB of prose - about a hundred times the worship
 * list. If a Client Component ever imported it, all 365 entries would be
 * serialised into the browser bundle to render ONE of them. The import above
 * makes that a build error rather than a slow page nobody profiles.
 *
 * Everything that reads this is a Server Component. The browser receives the
 * rendered HTML for the devotionals actually shown and none of the array.
 *
 * TENANT DATA IN CODE, ISOLATED SO IT CAN LEAVE CLEANLY. Same rule as
 * lib/worship-playlist.ts: this file holds the entries and nothing else. No
 * rendering code inlines one, and no component imports a specific entry -
 * components/site/devotional.tsx takes a Devotional and does not know where it
 * came from. Point the page at a per-church table and this file is deleted with
 * nothing else to change.
 *
 * The rotation logic deliberately lives elsewhere (lib/devotional-day.ts): it
 * is platform behaviour, identical for every tenant, and keeping it out of here
 * is what makes the data a clean lift.
 *
 * Extracted programmatically, never retyped. See the commit message for the
 * fidelity check.
 */

